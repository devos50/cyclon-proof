#!/usr/bin/env python3
"""Generate a source index; extraction does not certify mathematical claims."""
import argparse
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'paper/main.tex'
OUTLINE = re.compile(r'\\(section|subsection|subsubsection)\{([^\n]+)\}')
STATEMENTS = re.compile(r'\\begin\{(theorem|lemma|proposition|corollary)\}(?:\[([^\]]*)\])?')
LABELS = re.compile(r'\\label\{([^}]+)\}')
REFS = re.compile(r'\\(?:ref|eqref|pageref)\{([^}]+)\}')


def extract():
    source = SOURCE.read_text()
    line = lambda offset: source.count('\n', 0, offset) + 1
    headings = [dict(level=m[1], title=m[2], line=line(m.start()), offset=m.start()) for m in OUTLINE.finditer(source)]
    matches = list(STATEMENTS.finditer(source))
    statements = []
    for index, match in enumerate(matches):
        finish = source.find('\\end{' + match[1] + '}', match.end())
        body = source[match.end():finish]
        label = LABELS.search(body)
        reference_end = matches[index + 1].start() if index + 1 < len(matches) else len(source)
        context = [h for h in headings if h['offset'] <= match.start()]
        section = next((h['title'] for h in reversed(context) if h['level'] == 'section'), '')
        subsection = next((h['title'] for h in reversed(context) if h['level'] == 'subsection' and h['offset'] > next((x['offset'] for x in reversed(context) if x['level'] == 'section'), -1)), '')
        statements.append(dict(kind=match[1], title=' '.join((match[2] or '').split()), label=label[1] if label else None,
                               line=line(match.start()), section=section, subsection=subsection,
                               references=sorted(set(REFS.findall(source[match.end():reference_end])))))
    return dict(source='paper/main.tex', sha256=hashlib.sha256(source.encode()).hexdigest(),
                warning='Extracted source declarations and references; not a proof audit or a claim-status registry.',
                outline=[{k:v for k,v in h.items() if k != 'offset'} for h in headings], statements=statements)


def render(data):
    parts=['# Manuscript source index', '', 'Generated by `python3 tools/build_index.py`. Read [RESULTS.md](RESULTS.md) for claim status and model scope.',
           '', '**This index extracts declarations; it does not certify the proofs.** Cross-references in the JSON are not automatically logical dependencies.',
           '', 'Source SHA-256: `' + data['sha256'] + '`.', '', '## Outline', '']
    for h in data['outline']:
        indent = '  ' if h['level'] != 'section' else ''
        parts.append(f"{indent}- [{h['title']}](../paper/main.tex#L{h['line']})")
    parts += ['', '## Formal statements', '', '| Label | Declaration | Source |', '| --- | --- | --- |']
    for s in data['statements']:
        label = '`' + s['label'] + '`' if s['label'] else '(unlabelled)'
        title = (s['kind'].capitalize() + ': ' + s['title']).replace('|', r'\|')
        parts.append(f"| {label} | {title} | [line {s['line']}](../paper/main.tex#L{s['line']}) |")
    return '\n'.join(parts) + '\n'


def archive_index():
    lines = ['# Archive catalog', '', 'Generated by `python3 tools/build_index.py`.', '',
             '**Historical material only.** Statements here are not automatically current results. See [PARTIAL-RESULTS.md](PARTIAL-RESULTS.md), [RESULTS.md](RESULTS.md), and [the archive guide](../archive/README.md).', '',
             'Original filenames and checksums are preserved in [the migration manifest](MIGRATION-MANIFEST.json).', '']
    for folder in ('notes', 'fragments', 'experiments', 'pdf', 'build-logs'):
        lines += ['## ' + folder, '', '| Artifact | Topic / preserved filename |', '| --- | --- |']
        for path in sorted((ROOT / 'archive' / folder).iterdir()):
            topic = path.name
            if path.suffix == '.md':
                first = next((x.strip().lstrip('#').strip() for x in path.read_text(errors='replace').splitlines() if x.strip()), path.name)
                topic = first[:160]
            topic = topic.replace('|', r'\|')
            lines.append(f'| [{path.name}](../archive/{folder}/{path.name}) | {topic} |')
        lines.append('')
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if the committed index is stale')
    parser.add_argument('--query', help='print declarations matching a label or title')
    args = parser.parse_args()
    data = extract()
    if args.query:
        query = args.query.lower()
        for s in data['statements']:
            if query in ((s['label'] or '') + ' ' + s['title']).lower():
                print(json.dumps(s, ensure_ascii=False))
        return
    outputs = {ROOT / 'docs/MANUSCRIPT-INDEX.md': render(data), ROOT / 'docs/manuscript-index.json': json.dumps(data, indent=2) + '\n', ROOT / 'docs/ARCHIVE-INDEX.md': archive_index()}
    stale = []
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(content)
    if stale:
        raise SystemExit('Stale generated index: ' + ', '.join(stale))
    print(('Checked' if args.check else 'Generated') + f" index: {len(data['statements'])} declarations, {len(data['outline'])} headings")


if __name__ == '__main__':
    main()
